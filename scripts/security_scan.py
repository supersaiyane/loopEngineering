#!/usr/bin/env python3
"""Run explicit Trivy vulnerability checks and write a fail-closed sprint report."""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import subprocess
import sys

MARKER = '<!-- generated by security_scan.py -->'
MANIFESTS = {'pyproject.toml', 'poetry.lock', 'Pipfile.lock', 'uv.lock',
             'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml',
             'go.mod', 'go.sum', 'Cargo.lock', 'Gemfile.lock', 'composer.lock',
             'pom.xml', 'build.gradle', 'build.gradle.kts', 'gradle.lockfile'}
SKIP_DIRECTORIES = {'.git', '.venv', 'venv', 'node_modules', '.tox', '__pycache__',
                    '.mypy_cache', '.pytest_cache'}


def discover_manifests(root):
    found = []
    for directory, children, files in os.walk(root, followlinks=False):
        children[:] = [name for name in children if name not in SKIP_DIRECTORIES
                       and not (Path(directory) / name).is_symlink()]
        for name in files:
            if name in MANIFESTS or re.fullmatch(r'requirements(?:[-_.][A-Za-z0-9_.-]+)?\.txt', name):
                path = Path(directory) / name
                if not path.is_symlink():
                    found.append(path.relative_to(root).as_posix())
    return sorted(found)


def discover_dockerfiles(root):
    found = []
    for directory, children, files in os.walk(root, followlinks=False):
        children[:] = [name for name in children if name not in SKIP_DIRECTORIES
                       and not (Path(directory) / name).is_symlink()]
        for name in files:
            path = Path(directory) / name
            if (name == 'Dockerfile' or name.startswith('Dockerfile.') or name.endswith('.Dockerfile')) and not path.is_symlink():
                found.append(path.relative_to(root).as_posix())
    return sorted(found)


def scan(scanner, mode, target, root, scanners='vuln'):
    try:
        run = subprocess.run([scanner, mode, '--scanners', scanners, '--format', 'json', '--quiet', '--exit-code', '0', target], cwd=root, text=True, capture_output=True, timeout=600)
        if run.returncode:
            return None, 'scanner failed'
        data = json.loads(run.stdout)
        if not isinstance(data, dict) or not isinstance(data.get('Results'), list):
            return None, 'invalid or incomplete scanner output'
        return data, None
    except (OSError, ValueError, subprocess.TimeoutExpired):
        return None, 'scanner unavailable, timed out or returned invalid JSON'


def field(value):
    return str(value or 'Unknown').replace('|', '\\|').replace('\n', ' ')


def database_status(scanner, root, max_age_hours):
    """Inspect the database after scanning, since Trivy may update it during a scan."""
    try:
        run = subprocess.run([scanner, 'version', '--format', 'json'], cwd=root,
                             text=True, capture_output=True, timeout=60)
        data = json.loads(run.stdout) if run.returncode == 0 else {}
        updated = data.get('VulnerabilityDB', {}).get('UpdatedAt')
        # Trivy's Go timestamps may contain nine fractional digits, while older
        # supported Python versions accept at most six.
        normalized = re.sub(r'(\.\d{6})\d+(?=Z|[+-]\d\d:\d\d$)', r'\1', updated)
        timestamp = datetime.fromisoformat(normalized.replace('Z', '+00:00'))
        age = (datetime.now(timezone.utc) - timestamp).total_seconds() / 3600
        if age < -1 or age > max_age_hours:
            return {'status': 'blocked', 'updated_at': updated, 'reason': 'stale or future vulnerability database'}
        return {'status': 'current', 'updated_at': updated, 'scanner_version': data.get('Version')}
    except (OSError, ValueError, TypeError, AttributeError, subprocess.TimeoutExpired):
        return {'status': 'blocked', 'reason': 'vulnerability database freshness could not be verified'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', type=Path, default=Path.cwd())
    p.add_argument('--scanner', default='trivy')
    p.add_argument('--docker', default='docker')
    p.add_argument('--manifest', action='append', default=[])
    p.add_argument('--image', action='append', default=[])
    p.add_argument('--compose', action='append', default=[])
    p.add_argument('--no-images', action='store_true')
    p.add_argument('--secrets', action='store_true', help='Run a separate working-tree secret scan; store redacted findings only')
    p.add_argument('--max-db-age-hours', type=float, default=48)
    p.add_argument('sprint', type=int)
    args = p.parse_args()
    root = args.root.resolve(strict=True)
    if args.sprint < 1:
        raise ValueError('sprint must be positive')
    if not 0 < args.max_db_age_hours <= 720:
        raise ValueError('maximum database age must be between 0 and 720 hours')
    out = root / 'docs/reports' / f'sprint-{args.sprint}-security.md'
    if not out.resolve().is_relative_to(root) or out.is_symlink():
        raise ValueError('report path escapes the project')
    if out.exists() and not out.read_text(encoding='utf-8').startswith(MARKER):
        raise ValueError('refusing to replace a non-generated security report')
    raw = out.with_suffix('.json')
    if raw.is_symlink():
        raise ValueError('refusing to replace a symlinked security record')
    if raw.exists():
        try:
            previous = json.loads(raw.read_text(encoding='utf-8'))
        except ValueError:
            raise ValueError('refusing to replace a non-generated security record')
        if not isinstance(previous, dict) or previous.get('format') != 'loop-security-scan-v1':
            raise ValueError('refusing to replace a non-generated security record')
    lines = [MARKER, f'# Sprint {args.sprint}: security scan', '', f'Generated: {datetime.now(timezone.utc).isoformat()}', '',
             'Scope: explicit dependency manifests and images listed below. A clean scan cannot prove absence of unknown vulnerabilities. Scan coverage is limited to targets reported by the scanner.', '',
             '| Target | Result | Details |', '|---|---|---|']
    failures = []
    findings = []
    secret_findings = []
    discovered = discover_manifests(root)
    dockerfiles = discover_dockerfiles(root)
    declared = set()
    for manifest in args.manifest:
        path = (root / manifest).resolve()
        if path.is_relative_to(root):
            declared.add(path.relative_to(root).as_posix())
    for manifest in sorted(set(discovered) - declared):
        failures.append(f'{manifest}: NOT SCANNED (discovered manifest missing from declared inventory)')
    fs, error = scan(args.scanner, 'fs', str(root), root)
    if not args.manifest:
        failures.append('No dependency manifests declared for coverage verification')
    targets = [str(r.get('Target', '')) for r in fs.get('Results', []) if isinstance(r, dict)] if fs else []
    for manifest in args.manifest:
        path = (root / manifest).resolve()
        if not path.is_relative_to(root) or not path.is_file():
            failures.append(f'{manifest}: manifest missing or outside project')
        elif error or not any(t == manifest or t.endswith('/' + manifest) for t in targets):
            failures.append(f'{manifest}: NOT SCANNED (scanner unavailable or target not reported)')
        else:
            lines.append(f'| {field(manifest)} | Scanned | Dependency manifest reported by scanner |')
    if error:
        failures.append(f'Dependency scan: NOT SCANNED ({error})')
    scan_results = [('Dependencies', fs)] if fs else []
    image_inventory = set(args.image)
    if args.no_images and (args.image or args.compose):
        failures.append('Conflicting image inventory: --no-images with image or Compose targets')
    if args.no_images and dockerfiles:
        failures.append('Image inventory: NOT SCANNED (--no-images conflicts with Dockerfiles: ' + ', '.join(dockerfiles) + ')')
    if not args.no_images and not (args.image or args.compose):
        failures.append('Image inventory: NOT SCANNED (no images or Compose files declared)')
    for compose in args.compose:
        path = (root / compose).resolve()
        if not path.is_relative_to(root) or not path.is_file():
            failures.append(f'{compose}: NOT SCANNED (Compose file missing or outside project)')
            continue
        try:
            listing = subprocess.run([args.docker, 'compose', '-f', str(path), 'config', '--images'], cwd=root, capture_output=True, text=True, timeout=60)
            found = {line.strip() for line in listing.stdout.splitlines() if line.strip()}
            if listing.returncode or not found:
                failures.append(f'{compose}: NOT SCANNED (could not resolve images)')
            else:
                image_inventory.update(found)
        except (OSError, subprocess.TimeoutExpired):
            failures.append(f'{compose}: NOT SCANNED (Docker unavailable or timed out)')
    for image in sorted(image_inventory):
        if (not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._/:@-]*', image)
                or ('@' in image and not re.search(r'@sha256:[a-fA-F0-9]{64}$', image))):
            failures.append('Image target: NOT SCANNED (invalid image reference)')
            continue
        data, problem = scan(args.scanner, 'image', image, root)
        if problem or not data['Results']:
            failures.append(f'{image}: NOT SCANNED ({problem or "scanner returned no image results; coverage is unknown"})')
        else:
            lines.append(f'| {field(image)} | Scanned | Image digest must be checked against the deployed artifact |')
            scan_results.append((image, data))
    if args.no_images:
        lines.append('| Images | Not applicable (declared) | Confirm the project deploys no images |')
    if args.secrets:
        secret_scan, problem = scan(args.scanner, 'fs', str(root), root, scanners='secret')
        if problem:
            failures.append(f'Secret scan: NOT SCANNED ({problem})')
        else:
            for result in secret_scan['Results']:
                if not isinstance(result, dict) or not isinstance(result.get('Secrets', []), list):
                    failures.append('Secret scan: invalid finding results')
                    continue
                for secret in result.get('Secrets', []):
                    if not isinstance(secret, dict):
                        failures.append('Secret scan: invalid finding record')
                        continue
                    rule = secret.get('RuleID')
                    severity = secret.get('Severity')
                    line = secret.get('StartLine')
                    secret_findings.append({'target': result.get('Target', 'Unknown'),
                                            'rule': rule if isinstance(rule, str) and re.fullmatch(r'[A-Za-z0-9_.-]+', rule) else 'Unknown',
                                            'severity': severity if severity in ('UNKNOWN', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL') else 'UNKNOWN',
                                            'line': line if type(line) is int and line >= 0 else None})
            lines.append('| Working-tree secrets | Scanned | Findings are redacted; Git history is not covered |')
    else:
        lines.append('| Working-tree secrets | Not requested | Run with --secrets to scan; Git history is not covered |')
    database = database_status(args.scanner, root, args.max_db_age_hours)
    if database['status'] != 'current':
        failures.append('Scanner database: ' + database['reason'])
    else:
        lines.append(f"| Scanner database | Current | Updated {field(database['updated_at'])} |")
    for target, data in scan_results:
        for result in data['Results']:
            if not isinstance(result, dict) or not isinstance(result.get('Vulnerabilities', []), list):
                failures.append(f'{target}: invalid vulnerability results')
                continue
            for vuln in result.get('Vulnerabilities', []):
                if not isinstance(vuln, dict):
                    failures.append(f'{target}: invalid vulnerability record')
                    continue
                findings.append((target, vuln))
    for failure in failures:
        lines.append(f'| {field(failure)} | BLOCKED | Review and rerun |')
    lines.extend(['', '## Known findings', '', '| Target | ID | Severity | Package | Installed | Fixed |', '|---|---|---|---|---|---|'])
    for target, v in findings:
        lines.append('| ' + ' | '.join(field(x) for x in (target, v.get('VulnerabilityID'), v.get('Severity'), v.get('PkgName'), v.get('InstalledVersion'), v.get('FixedVersion'))) + ' |')
    if not findings:
        lines.append('| None reported | — | — | — | — | — |')
    lines.extend(['', '## Secret scan findings (redacted)', '', '| Target | Rule | Severity | Line |', '|---|---|---|---|'])
    for secret in secret_findings:
        lines.append('| ' + ' | '.join(field(secret.get(k)) for k in ('target', 'rule', 'severity', 'line')) + ' |')
    if not secret_findings:
        lines.append('| None reported or scan not requested | — | — | — |')
    lines.extend(['', f'Result: {"BLOCKED" if failures or findings or secret_findings else "No known findings in scanned targets"}. All severities are included; unscanned targets block this check.',
                  'Manifest and Dockerfile discovery excludes symlinked directories, Git metadata and dependency caches; other formats and image inventories require separate review. This report does not verify remediation or image digest.'])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    raw.write_text(json.dumps({'format': 'loop-security-scan-v1', 'sprint': args.sprint,
                               'generated_at': datetime.now(timezone.utc).isoformat(),
                               'status': 'blocked' if failures or findings or secret_findings else 'no-known-findings',
                               'failures': failures, 'discovered_manifests': discovered, 'discovered_dockerfiles': dockerfiles,
                               'database': database, 'secret_scan_requested': args.secrets,
                               'secret_findings': secret_findings, 'scans': dict(scan_results)}, indent=2) + '\n', encoding='utf-8')
    print(out)
    print(raw)
    return 1 if failures or findings or secret_findings else 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError) as exc:
        print(f'BLOCKED: {exc}', file=sys.stderr)
        sys.exit(1)
