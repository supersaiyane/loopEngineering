#!/usr/bin/env python3
"""Summarize local sprint records without claiming independent verification."""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import subprocess
import sys

MARKER = '<!-- generated by sprint_report.py -->'


def cell(value):
    return str(value if value is not None else 'Unknown').replace('|', '\\|').replace('\n', ' ')


def read_json(path):
    try:
        value = json.loads(path.read_text(encoding='utf-8'))
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def elapsed_minutes(events):
    """Pair completions with their own recorded attempt, not active agent effort."""
    starts, result = {}, {}
    for event in events:
        key = (event.get('task'), event.get('role'))
        if not all(isinstance(x, str) and x for x in key):
            continue
        action = event.get('action')
        if action == 'start':
            starts[key] = event.get('timestamp') if key not in starts else None
        elif action in ('block', 'retry'):
            starts.pop(key, None)
        elif action == 'complete':
            previous = starts.pop(key, None)
            try:
                start, end = (datetime.fromisoformat(value.replace('Z', '+00:00')) for value in (previous, event.get('timestamp')))
                if start.tzinfo is not None and end.tzinfo is not None and end >= start:
                    result[id(event)] = f'{(end - start).total_seconds() / 60:.1f} min'
            except (TypeError, ValueError, AttributeError):
                pass
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path.cwd())
    parser.add_argument('sprint', type=int)
    args = parser.parse_args()
    root = args.root.resolve(strict=True)
    if args.sprint < 1:
        raise ValueError('sprint must be positive')
    folder = root / 'docs' / f'sprint-{args.sprint}'
    if not folder.resolve().is_relative_to(root):
        raise ValueError('sprint directory escapes the project')
    cards = sorted((folder / 'stories').glob('*.md'))
    if not cards:
        raise ValueError('no sprint story cards found')
    if any(not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]*', p.stem) or not p.resolve().is_relative_to(root) for p in cards):
        raise ValueError('invalid story card path')
    out = root / 'docs/reports'
    if not out.resolve().is_relative_to(root):
        raise ValueError('report directory escapes the project')
    targets = [out / f'sprint-{args.sprint}-agents.md', out / f'sprint-{args.sprint}-git-tracker.md']
    for target in targets:
        if target.is_symlink() or (target.exists() and not target.read_text(encoding='utf-8').startswith(MARKER)):
            raise ValueError(f'refusing to overwrite a non-generated report: {target}')
    start, end = f'<!-- sprint-report-{args.sprint}:start -->', f'<!-- sprint-report-{args.sprint}:end -->'
    dashboards = {}
    for name, title in (('discipline-dashboard.md', 'Discipline dashboard'), ('baseline.md', 'Discipline baseline')):
        path = out / name
        if path.is_symlink():
            raise ValueError(f'refusing to write a symlinked dashboard: {path}')
        content = path.read_text(encoding='utf-8') if path.exists() else f'# {title}\n'
        if content.count(start) != content.count(end) or content.count(start) > 1:
            raise ValueError(f'dashboard has invalid generated section markers: {path}')
        if start in content and content.index(start) > content.index(end):
            raise ValueError(f'dashboard generated section markers are out of order: {path}')
        dashboards[path] = content
    repo = subprocess.run(['git', '-C', str(root), 'rev-parse', '--show-toplevel'], text=True, capture_output=True)
    if repo.returncode == 0 and Path(repo.stdout.strip()).resolve() == root:
        git = subprocess.run(['git', '-C', str(root), 'log', '--format=%H%x09%s'], text=True, capture_output=True)
        git_status = subprocess.run(['git', '-C', str(root), 'status', '--short', '--untracked-files=all'], text=True, capture_output=True)
    else:
        # Git searches parent directories; never attribute an enclosing repository to this project.
        git = git_status = subprocess.CompletedProcess(['git'], 1, '', 'project is not a Git repository root')
    commits = [line.split('\t', 1) for line in git.stdout.splitlines() if '\t' in line] if git.returncode == 0 else []
    ledger_paths = [root / '.loop/team-flow.json'] + sorted(folder.glob('*ledger*.json'))
    events, planned_tasks = [], []
    for path in ledger_paths:
        if path.resolve().is_relative_to(root):
            data = read_json(path)
            if isinstance(data.get('events'), list):
                events.extend(e for e in data['events'] if isinstance(e, dict))
            if isinstance(data.get('tasks'), dict):
                planned_tasks.extend((key, task) for key, task in data['tasks'].items() if isinstance(task, dict))
    elapsed = elapsed_minutes(events)
    lines = [MARKER, f'# Sprint {args.sprint}: agent contributions', '',
             'This report describes local handoff records. The ledger is not proof of an independent agent invocation or skill use.', '',
             '| Story | Role | Recorded event | Summary | Artifacts / handoffs | Claimed skill paths | Elapsed wall time |', '|---|---|---|---|---|---|---|']
    tracker = [MARKER, f'# Sprint {args.sprint}: Git and tracker', '',
               f'Generated: {datetime.now(timezone.utc).isoformat()}', '',
               'Local tracker records are not Jira issues. Evidence records report command results but do not independently prove adequacy or execution.', '',
               '| Story | Tracker status | Sync / Jira | Story commits | Command evidence |', '|---|---|---|---|---|']
    done_count = 0
    history_lines = []
    for card in cards:
        story = card.stem
        pattern = re.compile(r'(?<![A-Za-z0-9_-])' + re.escape(story) + r'(?![A-Za-z0-9_-])', re.I)
        matching = [(sha, title) for sha, title in commits if pattern.search(title)]
        record = read_json(folder / 'jira' / f'{story}.local.json')
        receipt = read_json(folder / 'jira' / f'{story}.json')
        if record.get('story_id') == story:
            status = record.get('status', 'Unknown')
            sync = f"Local {story} ({record.get('sync_state', 'unknown')}); docs/sprint-{args.sprint}/jira/{story}.local.json"
            events_for_story = record.get('events')
            if isinstance(events_for_story, list) and events_for_story:
                for event in events_for_story:
                    if isinstance(event, dict):
                        history_lines.append('| ' + ' | '.join(cell(v) for v in (story, event.get('timestamp'), event.get('status'), event.get('note'))) + ' |')
                    else:
                        history_lines.append(f'| {cell(story)} | Unknown | Unknown | Invalid event |')
            else:
                history_lines.append(f'| {cell(story)} | Unknown | Unknown | No local event history |')
        elif receipt.get('key'):
            status = 'Unknown (no live Jira readback)'
            sync = f"Jira receipt {receipt['key']} (not verified)"
        else:
            status, sync = 'Unknown', 'No tracker record'
        if str(status).lower() == 'done':
            done_count += 1
        ev = read_json(folder / 'evidence' / f'{story}.json')
        matching_shas = {sha for sha, _ in matching}
        if ev.get('story_id') == story and ev.get('commit') in matching_shas and type(ev.get('exit_code')) is int and isinstance(ev.get('command'), list) and ev['command']:
            check = f"Recorded exit {ev['exit_code']} at {ev['commit'][:12]}"
        else:
            check = 'Unknown / missing matching evidence'
        history = '; '.join(f'{sha[:12]} {title}' for sha, title in matching) or ('Unknown (Git unavailable)' if git.returncode else 'No story-linked commit')
        tracker.append('| ' + ' | '.join(map(cell, (story, status, sync, history, check))) + ' |')
        matched = [e for e in events if str(e.get('task', '')) == story
                   or str(e.get('task', '')).startswith(story + '-')
                   or str(e.get('task', '')).startswith(story + '_')]
        planned = [(key, task) for key, task in planned_tasks
                   if key == story or key.startswith(story + '-') or key.startswith(story + '_')]
        event_tasks = {event.get('task') for event in matched}
        for key, task in planned:
            if key not in event_tasks:
                lines.append('| ' + ' | '.join(map(cell, (story, task.get('role'), 'Planned: ' + str(task.get('status', 'unknown')), 'No recorded handoff', ', '.join(task.get('declared_outputs', [])) or 'Unknown', 'Unknown', 'Unknown'))) + ' |')
        if not matched and not planned:
            lines.append(f'| {cell(story)} | Unknown | No recorded handoff | Unknown | Unknown | Unknown | Unknown |')
        for event in matched:
            skills = event.get('claimed_skills')
            skill_paths = ', '.join(sorted(skills)) if isinstance(skills, dict) and skills else 'Not recorded'
            artifacts = []
            for name in ('outputs', 'handoff'):
                value = event.get(name)
                if isinstance(value, dict):
                    artifacts.extend(str(path) for path in value)
            duration = elapsed.get(id(event), 'Unknown') if event.get('action') == 'complete' else 'Unknown'
            lines.append('| ' + ' | '.join(map(cell, (story, event.get('role', 'Unknown'), event.get('action', 'Unknown'), event.get('summary', 'Not recorded'), ', '.join(artifacts) or 'Not recorded', skill_paths, duration))) + ' |')
    lines.extend(['', 'Elapsed wall time is derived from recorded start and completion events; it includes waiting and does not establish active effort. Agent calls and skills used remain unverified unless independently checked in the host.'])
    tracker.extend(['', '## Local tracker events', '', '| Story | Timestamp | Status | Note |', '|---|---|---|---|'])
    tracker.extend(history_lines or ['| Unknown | Unknown | Unknown | No local tracker events available |'])
    tracker.extend(['', '## Working tree at report generation', '',
                    'Paths are a snapshot taken before these reports were written; review Git status again before committing.', ''])
    if git_status.returncode:
        tracker.append('Unknown: Git status could not be read.')
    elif git_status.stdout:
        tracker.extend(['```text', git_status.stdout.rstrip(), '```'])
    else:
        tracker.append('No changes reported by Git at the time of the snapshot.')
    out.mkdir(parents=True, exist_ok=True)
    for target, content in zip(targets, (lines, tracker)):
        target.write_text('\n'.join(content) + '\n', encoding='utf-8')
        print(target)
    block = (f'{start}\n### Sprint {args.sprint} recorded tracker status\n\n'
             f'- Stories locally recorded Done: {done_count} / {len(cards)}.\n'
             '- Independent QA, Jira synchronization, memory compliance and sprint closure: unknown until verified.\n'
             f'- Details: [agent contributions](sprint-{args.sprint}-agents.md), '
             f'[Git and tracker](sprint-{args.sprint}-git-tracker.md).\n{end}')
    for dashboard, content in dashboards.items():
        if start in content:
            left, rest = content.split(start, 1)
            _, right = rest.split(end, 1)
            content = left + block + right
        else:
            content = content.rstrip() + '\n\n' + block + '\n'
        dashboard.write_text(content, encoding='utf-8')
        print(dashboard)


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError) as exc:
        print(f'BLOCKED: {exc}', file=sys.stderr)
        sys.exit(1)
