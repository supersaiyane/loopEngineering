#!/usr/bin/env python3
"""Index foundation documents and summarize recorded sprint plans."""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from datetime import datetime, timezone

MARKER = '<!-- generated by project_index.py -->'
ORDER = ['coordinator-brief.md', 'market-research.md', 'tech-strategy.md', 'prd.md', 'app-flow.md',
         'architecture.md', 'system_design.md', 'db-schema.md', 'cloud-architecture.md',
         'security-posture.md', 'testing-strategy.md', 'finops.md', 'sm-gate.md', 'roadmap.md', 'project-index.md']


def text_cell(value):
    return str('Unknown' if value is None or value == '' else value).replace('|', '\\|').replace('\n', ' ')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', type=Path, default=Path.cwd())
    p.add_argument('--record', action='append', default=[], help='Record an existing foundation document when created')
    args = p.parse_args()
    root = args.root.resolve(strict=True)
    folder = root / 'docs/foundation'
    if not folder.resolve().is_relative_to(root):
        raise ValueError('foundation directory escapes project')
    index, report = folder / 'INDEX.md', folder / 'project-work-report.md'
    for path in (index, report):
        if path.is_symlink() or (path.exists() and not path.read_text(encoding='utf-8').startswith(MARKER)):
            raise ValueError(f'refusing to overwrite a non-generated document: {path}')
    plan_path = folder / 'sprint-plan.json'
    planned = []
    if plan_path.exists():
        if not plan_path.resolve().is_relative_to(root):
            raise ValueError('sprint plan escapes project')
        plan = json.loads(plan_path.read_text(encoding='utf-8'))
        if not isinstance(plan, dict) or not isinstance(plan.get('sprints'), list):
            raise ValueError('invalid sprint plan')
        seen = set()
        for sprint in plan['sprints']:
            if not isinstance(sprint, dict) or type(sprint.get('number')) is not int or sprint['number'] < 1 or sprint['number'] in seen:
                raise ValueError('invalid or duplicate sprint number')
            seen.add(sprint['number'])
            if not isinstance(sprint.get('stories', []), list) or not all(isinstance(x, str) for x in sprint.get('stories', [])) or not isinstance(sprint.get('stages', []), list):
                raise ValueError('invalid sprint stories or stages')
            for stage in sprint.get('stages', []):
                if not isinstance(stage, dict):
                    raise ValueError('invalid stage')
                for key in ('planned_days', 'actual_days'):
                    if stage.get(key) is not None and (type(stage[key]) not in (int, float) or not 0 <= stage[key] <= 10000):
                        raise ValueError('invalid stage duration')
            planned.append(sprint)
    present = {p.name: p for p in folder.glob('*.md') if p.name not in (index.name, report.name) and p.resolve().is_relative_to(root)}
    ledger_path = root / '.loop/foundation-sequence.json'
    if not ledger_path.resolve().is_relative_to(root) or ledger_path.is_symlink():
        raise ValueError('sequence ledger escapes project')
    for name in args.record:
        if name not in present or Path(name).name != name:
            raise ValueError(f'cannot record missing or unsafe foundation document: {name}')
    ledger_path.parent.mkdir(parents=True, exist_ok=True)
    lock = ledger_path.parent / 'foundation-sequence.lock'
    fd = os.open(str(lock), os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    os.close(fd)
    try:
        ledger = json.loads(ledger_path.read_text()) if ledger_path.exists() else {'version': 1, 'documents': []}
        if not isinstance(ledger, dict) or not isinstance(ledger.get('documents'), list):
            raise ValueError('invalid sequence ledger')
        recorded = {e['path'] for e in ledger['documents']}
        for name in args.record:
            if name not in recorded:
                ledger['documents'].append({'path': name, 'recorded_at': datetime.now(timezone.utc).isoformat()})
                recorded.add(name)
        tmp_fd, tmp_path = tempfile.mkstemp(prefix='.foundation-', dir=ledger_path.parent)
        try:
            with os.fdopen(tmp_fd, 'w') as stream:
                json.dump(ledger, stream, indent=2)
                stream.write('\n')
            os.replace(tmp_path, ledger_path)
        finally:
            if os.path.exists(tmp_path):
                os.unlink(tmp_path)
    finally:
        lock.unlink()
    lines = [MARKER, '# Foundation index', '', 'Sequence records the order documents were registered, not independently verified creation times. Unregistered documents have unknown order.', '', '| Sequence | Document | Owner / status |', '|---|---|---|']
    for i, entry in enumerate(ledger['documents'], 1):
        name = entry['path']
        lines.append(f'| {i:02d} | [{name}]({name}) | {"Unknown" if name in present else "Missing"} |')
    for name in [n for n in ORDER if n in present and n not in recorded] + sorted(set(present) - set(ORDER) - recorded):
        lines.append(f'| Unknown | [{name}]({name}) | Unknown |')
    work = [MARKER, '# Project work report', '', 'Recorded statuses and roles are local data, not independently verified agent activity. Story points are not days.', '']
    if planned:
        work += ['## Planned sprints', '', 'Values below are supplied in sprint-plan.json; reported actual time requires its own evidence.', '']
        for sprint in sorted(planned, key=lambda item: item['number']):
            work += [f"### Sprint {sprint['number']}", '', f"Goal: {text_cell(sprint.get('goal'))}",
                     f"Stories: {text_cell(', '.join(sprint.get('stories', [])))}", '',
                     '| Stage | Role | Planned days | Reported actual days | Evidence |', '|---|---|---|---|---|']
            for stage in sprint.get('stages', []):
                work.append('| ' + ' | '.join(text_cell(stage.get(k)) for k in ('stage', 'role', 'planned_days', 'actual_days', 'evidence')) + ' |')
            if not sprint.get('stages'):
                work.append('| Unknown | Unknown | Unknown | Unknown | Unknown |')
            work.append('')
    sprint_dirs = []
    for path in (root / 'docs').glob('sprint-*'):
        match = re.fullmatch(r'sprint-([1-9][0-9]*)', path.name)
        if match and path.is_dir() and path.resolve().is_relative_to(root):
            sprint_dirs.append((int(match.group(1)), path))
    if not sprint_dirs:
        work.append('No sprint story directories recorded.')
    for number, path in sorted(sprint_dirs):
        work += [f'## Sprint {number}', '', '| Story | Title | Planned roles | Recorded tracker status | Estimated effort / duration | Actual time |', '|---|---|---|---|---|---|']
        cards = sorted((path / 'stories').glob('*.md'))
        if not cards:
            work.append('| Unknown | No story cards found | Unknown | Unknown | Unknown | Unknown |')
        for card in cards:
            if not card.resolve().is_relative_to(root):
                raise ValueError(f'story path escapes project: {card}')
            content = card.read_text(encoding='utf-8')
            title = next((s.lstrip('# ').strip() for s in content.splitlines() if s.strip()), card.stem)
            roles = re.search(r'^\s*[-*]?\s*\*\*Roles:\*\*\s*(.+)$', content, re.I | re.M)
            tracker = path / 'jira' / f'{card.stem}.local.json'
            status = 'Unknown'
            if tracker.resolve().is_relative_to(root):
                try:
                    record = json.loads(tracker.read_text(encoding='utf-8'))
                    if record.get('story_id') == card.stem:
                        status = record.get('status') or 'Unknown'
                except (OSError, ValueError, AttributeError):
                    pass
            work.append('| ' + ' | '.join(text_cell(x) for x in (card.stem, title, roles.group(1) if roles else 'Unknown', status, 'Unknown', 'Unknown')) + ' |')
        work.append('')
    folder.mkdir(parents=True, exist_ok=True)
    index.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    report.write_text('\n'.join(work) + '\n', encoding='utf-8')
    print(index)
    print(report)


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError) as exc:
        print(f'BLOCKED: {exc}', file=sys.stderr)
        sys.exit(1)
